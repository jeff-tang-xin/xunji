-- ============================================================
-- V23: 项目模板分层语义（模板=通用层，项目实例=边界层）
--   ① project_template 加 builtin：内置模板（standard/minimal）不可删除
--   ② project_template_node 加通用层四字段：
--        standards / requirements = JSONB 字符串数组（可判定的规范与要求）
--        methodology             = TEXT（可执行步骤的方法论）
--        deliverable             = VARCHAR(256)（具体产出物名）
--     这四者是跨项目可复用、喂给 AI 的阶段指导知识，不含本项目任务边界
--   ③ project_work_node 加 scope TEXT：项目实例的「本阶段做什么、范围到哪」，
--      创建项目时填入，模板不写死任务边界
--   ④ 给内置 standard(10) + minimal(6) 共 16 个节点回填实质性内容
--
--   幂等：ADD COLUMN IF NOT EXISTS；UPDATE 按 (code, type, seq) 定位，可重复执行
--   语法坑：UPDATE ... FROM 的多源用隐式 CROSS JOIN
--           （FROM t, (VALUES ...) AS v(...) WHERE ...），不要 JOIN+WHERE 混用（V20 曾报错）
-- ============================================================

-- ---------- ① 模板主表：内置标记 ----------
ALTER TABLE project_template ADD COLUMN IF NOT EXISTS builtin BOOLEAN NOT NULL DEFAULT false;

UPDATE project_template SET builtin = true WHERE code IN ('standard', 'minimal');

-- ---------- ② 模板节点：通用层字段 ----------
ALTER TABLE project_template_node ADD COLUMN IF NOT EXISTS standards    JSONB;
ALTER TABLE project_template_node ADD COLUMN IF NOT EXISTS requirements JSONB;
ALTER TABLE project_template_node ADD COLUMN IF NOT EXISTS methodology  TEXT;
ALTER TABLE project_template_node ADD COLUMN IF NOT EXISTS deliverable  VARCHAR(256);

-- ---------- ③ 项目实例节点：边界层字段 ----------
ALTER TABLE project_work_node ADD COLUMN IF NOT EXISTS scope TEXT;

